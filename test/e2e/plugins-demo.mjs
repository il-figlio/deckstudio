// Plugins tab in the browser demo: built-ins, bundled marketplace, simulated install / enable / grant / run, templates, inspector.
import { launch, args, shotPath } from './lib.mjs'
const { url: URL, sp: SP } = args()
const sleep = ms => new Promise(r => setTimeout(r, ms))
let pass = 0, fail = 0
const ok = (w, c, n = '') => { c ? pass++ : fail++; console.log(`${c ? 'PASS' : 'FAIL'}  ${w.padEnd(52)} ${n}`) }
const b = await launch()
const page = await b.newPage({ viewport: { width: 1500, height: 1000 } })
const errs = []; page.on('pageerror', e => errs.push(e.message))
const keyImg = async i => page.locator('[data-ds-key]').nth(i).locator('img').getAttribute('src').catch(() => 'blank')
const open = async () => { await page.locator('[data-ds-topbar] button:has-text("plugins")').click(); await sleep(900) }
try {
  await page.goto(URL); await page.evaluate(() => localStorage.clear()); await page.reload()
  await page.waitForSelector('[data-ds-key] img', { timeout: 15000 }); await sleep(1200)
  await open()
  const ids = await page.locator('[data-ds-plugin]').evaluateAll(els => els.map(e => e.getAttribute('data-id')))
  ok('demo lists the bundled built-ins only', ids.join() === ['bots', 'capture', 'grokbot'].sort().join() || ['bots', 'capture', 'grokbot'].every(i => ids.includes(i)) && !ids.some(i => i.startsWith('ante')), ids.join())
  await page.screenshot({ path: shotPath(SP, `plugins-demo-list.png`) })
  await page.locator('[data-ds-plugin][data-id="capture"] [data-ds-recipe-head]').click(); await sleep(400)
  ok('capture shows values + actions', (await page.locator('[data-ds-plugin][data-id="capture"] [data-ds-plugin-action]').count()) > 5)
  await page.locator('[data-ds-plugins] [data-kit="segment"][data-value="marketplace"]').click(); await sleep(800)
  const mk = page.locator('[data-ds-market]')
  ok('marketplace shows the bundled registry copy', (await mk.count()) >= 1, `${await mk.count()} entries`)
  await page.screenshot({ path: shotPath(SP, `plugins-demo-marketplace.png`) })
  const first = mk.first(); const id = await first.getAttribute('data-id')
  await first.locator('button:has-text("install")').click(); await sleep(1200)
  const card = page.locator(`[data-ds-plugin][data-id="${id}"]`)
  ok(`install ${id} (simulated) → installed tab, off`, (await card.count()) === 1 && /disabled/.test(await card.locator('[data-ds-pill]').first().innerText()))
  await card.locator('[role="switch"]').click(); await sleep(600)
  ok('enable asks first', (await page.locator('[data-ds-confirm]').count()) === 1)
  await page.screenshot({ path: shotPath(SP, `plugins-demo-enable.png`) })
  await page.locator('[data-ds-confirm] button:has-text("switch on")').click(); await sleep(900)
  ok('enabled', /ok/.test(await card.locator('[data-ds-pill]').first().innerText()))
  await card.locator('[data-ds-plugin-action] button:has-text("run")').first().click(); await sleep(900)
  ok('run action in demo says what it would do', /would|ran/i.test((await page.locator('[data-kit="toast"]').allTextContents()).join(' ')), (await page.locator('[data-kit="toast"]').allTextContents()).join(' / ').slice(-90))
  // template → key 1
  await page.locator('[data-ds-plugins] [data-kit="segment"][data-value="installed"]').click().catch(() => {}); await sleep(200)
  const k0 = await keyImg(0)
  await card.locator('[data-ds-plugin-sec]:has(h4:text-is("templates")) button:has-text("add to key")').first().click(); await sleep(1500)
  ok('template "add to key 1" applies', (await keyImg(0)) !== k0)
  await page.screenshot({ path: shotPath(SP, `plugins-demo-card.png`) })
  await page.keyboard.press('Escape'); await sleep(300)
  ok('escape closes panel', (await page.locator('[data-ds-plugins]').count()) === 0)
  // inspector on that key: plugin action fields + binding
  await page.locator('[data-ds-key]').nth(0).click(); await sleep(600)
  const insp = page.locator('[data-ds-inspector]')
  ok('inspector: plugin action shows plugin + action pickers', (await insp.locator('[data-ds-action] [data-kit="label"]:text-is("plugin")').count()) >= 1 && (await insp.locator('[data-ds-action] [data-kit="label"]:text-is("action")').count()) >= 1)
  ok('inspector: plugin binding group present', (await insp.locator('legend:text-is("plugin")').count()) === 1)
  const kb = await keyImg(0)
  await insp.locator('[data-ds-plugin-vars] [data-ds-chip]').first().click(); await sleep(1200)
  ok('value chip inserts a {id.value} into the label', kb && /\{[a-z0-9-]+\.\w+\}/.test(await insp.locator('[data-kit="field"]:has([data-kit="label"]:text-is("label")) input').inputValue()), await insp.locator('[data-kit="field"]:has([data-kit="label"]:text-is("label")) input').inputValue())
  await insp.locator('[data-ds-plugin-vars]').scrollIntoViewIfNeeded()
  await page.screenshot({ path: shotPath(SP, `plugins-demo-inspector.png`) })
  await insp.locator('[data-ds-action]').first().scrollIntoViewIfNeeded()
  await page.screenshot({ path: shotPath(SP, `plugins-demo-inspector-action.png`) })
  // persists in this browser
  await page.reload(); await page.waitForSelector('[data-ds-key] img'); await sleep(1200)
  await open()
  ok('install + enable persist across reload (localStorage)', /ok/.test(await page.locator(`[data-ds-plugin][data-id="${id}"] [data-ds-pill]`).first().innerText().catch(() => '')))
  const c2 = page.locator(`[data-ds-plugin][data-id="${id}"]`)
  await c2.locator('[data-ds-recipe-head]').click(); await sleep(300)
  await c2.locator('button:has-text("uninstall")').click(); await sleep(300)
  await page.locator('[data-ds-confirm] button:has-text("uninstall")').click(); await sleep(900)
  ok('uninstall (simulated)', (await page.locator(`[data-ds-plugin][data-id="${id}"]`).count()) === 0)
  // built-in grant path: none of the built-ins declare permissions, so check the API refuses undeclared grants
  const g = await page.evaluate(async () => (await fetch('/api/plugins/capture/grant', { method: 'POST', body: JSON.stringify({ shell: true }) })).json())
  ok('undeclared grant refused', /doesn't declare/.test(g.error || ''), g.error)
} catch (e) { ok('script', false, e.message.split('\n')[0]); await page.screenshot({ path: shotPath(SP, `plugins-demo-error.png`) }) }
console.log(errs.length ? 'PAGE ERRORS: ' + errs.slice(0, 3).join(' | ') : 'no page errors')
console.log(`\n${pass}/${pass + fail} passed`)
await b.close()
process.exit(fail ? 1 : 0)
